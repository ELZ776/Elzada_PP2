#Basic Slicing (start:end)-----------------------------------------------------------------------------------------------------
b = "Hello, World!"
print(b[1:4])  

b = "Python Programming"
print(b[3:7])  

#Slice From the Start (:end)-------------------------------------------------------------------------------------------------------------------------------
b = "Hello, World!"
print(b[:5])  # Hello

#Slice To the End (start:)--------------------------------------------------------------------------------------------------------------------------
b = "Computer"
print(b[4:])  

#Negative Indexing----------------------------------------------------------------------------------------------------------------------
b = "Hello, World!"
print(b[-6:-2])
