#Basic Concatenation------------------------------------------------------------------------------------------------------------------------------
a = "Good"
b = "Morning"
c = a + b
print(c) 

#Adding Spaces Between Strings--------------------------------------------------------------------------------------------------------------------------
a = "Good"
b = "luck"
c = a + " " + b
print(c)

#Concatenating Multiple Strings----------------------------------------------------------------------------------------------------------------------
word1 = "Today"
word2 = "is"
word3 = "sunny"
sentence = word1 + " " + word2 + " " + word3
print(sentence)
