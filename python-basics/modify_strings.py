#upper() - Convert to Uppercase-------------------------------------------------------------------------------------------------------------------------------
text = "hello"
print(text.upper())

#lower() - Convert to Lowercase--------------------------------------------------------------------------------------------------------------------------
text = "WORLD"
print(text.lower())


#strip() - Remove Whitespace----------------------------------------------------------------------------------------------------------------------
text = "  hello  "
print(text.strip())

#replace() - Replace Text-------------------------------------------------------------------------------------------------------------------------------
text = "This is bad weather"
print(text.replace("bad", "good"))

#split() - Split String into List--------------------------------------------------------------------------------------------------------------------------
text = "Hello, World!"
print(text.split(","))


