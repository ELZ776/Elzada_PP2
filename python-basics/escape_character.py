#Backslash (\)----------------------------------------------------------------------------------------------------------------------
txt = "folder\\file.txt"
print(txt) 

#New Line (\n)----------------------------------------------------------------------------------------------------------------------
txt = "Hello\nWorld"
print(txt)

#Tab (\t)----------------------------------------------------------------------------------------------------------------------
txt = "Hello\tWorld"
print(txt)

#Double Quotes Inside Double Quotes (")----------------------------------------------------------------------------------------------------------------------
txt = "He said \"Hello\""
print(txt)